  /* The CSS height is locked into data-h on first sight. Reading it back from
     the height attribute would compound by devicePixelRatio on every repaint,
     which is what made these canvases grow taller each frame. */
  function fit(cv){
    var dpr = window.devicePixelRatio || 1;
    var base = parseInt(cv.getAttribute('data-h'), 10);
    if(!base){
      base = parseInt(cv.getAttribute('height'), 10) || 220;
      cv.setAttribute('data-h', base);
    }
    var w = cv.clientWidth || cv.parentNode.clientWidth || 520;
    /* shorter panels on small screens so the section stays scannable */
    var h = window.innerWidth < 560 ? Math.round(base * 0.74)
          : window.innerWidth < 900 ? Math.round(base * 0.87) : base;
    cv.style.width = '100%';
    cv.style.height = h + 'px';
    var bw = Math.max(1, Math.round(w * dpr)), bh = Math.max(1, Math.round(h * dpr));
    if(cv.width !== bw) cv.width = bw;
    if(cv.height !== bh) cv.height = bh;
    var g = cv.getContext('2d');
    g.setTransform(dpr, 0, 0, dpr, 0, 0);
    g.clearRect(0, 0, w, h);
    return { g:g, w:w, h:h };
  }
