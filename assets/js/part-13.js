  /* Abramowitz & Stegun 7.1.26 normal CDF */
  function ncdf(x){
    var t = 1 / (1 + 0.2316419 * Math.abs(x));
    var d = 0.3989422804014327 * Math.exp(-x * x / 2);
    var p = d * t * (0.319381530 + t * (-0.356563782 + t * (1.781477937 + t * (-1.821255978 + t * 1.330274429))));
    return x >= 0 ? 1 - p : p;
  }
  function npdf(x){ return 0.3989422804014327 * Math.exp(-x * x / 2); }

  /* Black-Scholes-Merton — price + full Greek set */
  function bsm(S, K, T2, sig, r, isCall){
    if(T2 <= 0 || sig <= 0){
      var intr = isCall ? Math.max(0, S - K) : Math.max(0, K - S);
      return { price:intr, delta:isCall ? (S > K ? 1 : 0) : (S < K ? -1 : 0), gamma:0, theta:0, vega:0 };
    }
    var sq = Math.sqrt(T2);
    var d1 = (Math.log(S / K) + (r + sig * sig / 2) * T2) / (sig * sq);
    var d2 = d1 - sig * sq;
    var disc = Math.exp(-r * T2);
    var price = isCall
      ? S * ncdf(d1) - K * disc * ncdf(d2)
      : K * disc * ncdf(-d2) - S * ncdf(-d1);
    var gamma = npdf(d1) / (S * sig * sq);
    var vega  = S * npdf(d1) * sq / 100;                 /* per 1 vol point */
    var theta = (-(S * npdf(d1) * sig) / (2 * sq)
      + (isCall ? -1 : 1) * r * K * disc * (isCall ? ncdf(d2) : ncdf(-d2))) / 365;
    return { price:price, delta:isCall ? ncdf(d1) : ncdf(d1) - 1, gamma:gamma, theta:theta, vega:vega, d1:d1, d2:d2 };
  }

